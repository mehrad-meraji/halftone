// Regenerates the built-in icon data inside src/components/icon/icon.ts from
// @phosphor-icons/core (MIT). Edit NAMES to change what ships; then `npm run icons`.
// The data stays inside icon.ts so the component remains a single copyable file.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const assets = join(root, 'node_modules/@phosphor-icons/core/assets');
const WEIGHTS = ['regular', 'bold', 'fill'];

const NAMES = `
arrow-down arrow-left arrow-right arrow-square-out arrow-up arrow-up-right
bell bug calendar caret-down caret-left caret-right caret-up check check-circle
chat-circle clock cloud code copy dots-three download-simple envelope eye eye-slash
flag funnel gear github-logo google-logo house info link list lock magnifying-glass
minus pencil-simple plus question rocket sign-out star terminal trash user
warning warning-circle x x-circle
`.trim().split(/\s+/);

const inner = (weight, name) => {
  const file = join(assets, weight, weight === 'regular' ? `${name}.svg` : `${name}-${weight}.svg`);
  if (!existsSync(file)) throw new Error(`missing ${weight}/${name}`);
  return readFileSync(file, 'utf8').replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
};

const q = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const lines = [];
for (const name of NAMES) {
  const parts = WEIGHTS.map((w) => `${w}: ${q(inner(w, name))}`);
  lines.push(`  ${/^[a-z]+$/.test(name) ? name : q(name)}: {\n    ${parts.join(',\n    ')},\n  },`);
}
const block = `// <icons:start> generated by scripts/build-icons.mjs from @phosphor-icons/core (MIT)\nBUILT_IN = {\n${lines.join('\n')}\n};\n// <icons:end>`;

const target = join(root, 'src/components/icon/icon.ts');
const src = readFileSync(target, 'utf8');
const next = src.replace(/\/\/ <icons:start>[\s\S]*?\/\/ <icons:end>/, () => block);
if (next === src && !src.includes('<icons:start>')) throw new Error('markers missing in icon.ts');
writeFileSync(target, next);
console.log(`icons: ${NAMES.length} names x ${WEIGHTS.length} weights, ${(block.length / 1024).toFixed(1)} kB`);
